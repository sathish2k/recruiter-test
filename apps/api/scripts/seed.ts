async function seed(): Promise<void> {
  await connectDb();
  await ClientModel.deleteMany({ agencyId: AGENCY });
  await ClientModel.insertMany(
    clients.map((c) => ({ ...c, agencyId: AGENCY })),
  );
  await JobModel.deleteMany({ agencyId: AGENCY });
  await JobModel.insertMany(jobs.map((j) => ({ ...j, agencyId: AGENCY })));
  await CandidateModel.deleteMany({ agencyId: AGENCY });
  await CandidateModel.insertMany(
    candidates.map((c) => ({ ...c, agencyId: AGENCY })),
  );
  console.log(
    `Seeded ${clients.length} clients, ${jobs.length} jobs, ${candidates.length} candidates.`,
  );
  await closeDb();
}

await seed();
